"""
[백트래킹 - 조합 생성]

▣ 문제 설명
- 1, 2, ..., n 의 숫자 중에서 k 개를 골라 만들 수 있는 모든 "조합" 을 출력합니다.
- 조합은 "순서 없이 어떤 것을 골랐는가" 만 따집니다.
  예) [1, 2] 와 [2, 1] 은 같은 조합으로 봅니다.

▣ 입력
- n: 전체 숫자 개수 (1, 2, ..., n)
- k: 그 중 골라야 할 개수

▣ 출력
- 가능한 모든 조합을 담은 리스트.

▣ 작은 예시 (n = 4, k = 2)
가능한 조합:
    [1, 2], [1, 3], [1, 4], [2, 3], [2, 4], [3, 4]
모두 6 개.

==============================================================================
▣ 백트래킹이 뭐예요? — 미로 탐색에 비유해 보세요.
==============================================================================
탐험가가 갈림길에서 한쪽 길을 "선택" 하고 끝까지 가본 다음, 막다른 길이면
한 걸음 되돌아와서 "다른 길" 을 시도하는 방식이 바로 백트래킹입니다.

"선택(Choose) → 탐색(Explore) → 취소(Unchoose, 되돌리기)" 세 단계 패턴.

조합 생성도 똑같습니다.
"숫자 하나를 골라 보고, 그 뒤로 더 큰 숫자에서 또 골라 보다가, k 개가 채워지면 기록.
 다 못 채우면 마지막 선택을 취소(되돌려) 다른 숫자를 시도".

==============================================================================
▣ 결정 트리 시각화 (n = 3, k = 2)
==============================================================================
                  [ 아직 아무것도 안 고름 ]
                  /        |          \\
                1을 고름   2를 고름     3을 고름
                /   \\      |
             2고름  3고름  3고름
             ↓      ↓      ↓
           [1,2]  [1,3]  [2,3]    <- k=2 도달, 결과로 추가!

==============================================================================
▣ 자주 묻는 질문: "2를 고른 다음에 1은 왜 고르면 안 되나요?"
==============================================================================
조합(Combination) 은 "순서 상관없이 어떤 것을 골랐는가" 만 보는 것입니다.
따라서 [1, 2] 와 [2, 1] 은 동일한 조합으로 취급됩니다.

만약 "2를 고른 뒤에 1도 다시 고를 수 있다" 고 허용하면 어떻게 될까요?

  ❌ 잘못된 방식 (start 규칙이 없을 때)
                [    아직 아무것도 안 고름    ]
                /          |            \
             1 고름       2 고름        3 고름
             /  \         / \           / \
           2    3        1   3         1   2     ← 자기보다 작은 수까지 또 시도
           ↓    ↓        ↓   ↓         ↓   ↓
         [1,2] [1,3]   [2,1][2,3]    [3,1][3,2]
                          └─ [1,2] 와 중복!     └─ [1,3], [2,3] 과 중복!

→ [1,2] 와 [2,1] 이 둘 다 만들어져 같은 조합이 두 번 나옵니다. 중복!

  ✅ 올바른 방식 (start = num + 1 규칙)
                [    아직 아무것도 안 고름   ]
                /          |            \
             1 고름       2 고름         3 고름
             /  \          |
           2    3         3              (n=3 이라 더 시도할 수 없음)
           ↓    ↓         ↓
         [1,2] [1,3]    [2,3]            ← 각 조합이 딱 한 번만!

→ "이미 고른 수보다 더 큰 수만 본다" 는 한 줄 규칙으로 중복이 자동 제거됩니다.

비교: 만약 "1을 다시 고르도록 허용" 하면 그건 조합이 아니라 "순열(Permutation)" 이
됩니다. (n=3, k=2 의 순열 결과는 [1,2], [1,3], [2,1], [2,3], [3,1], [3,2] 6개.
조합은 [1,2], [1,3], [2,3] 의 3개.)

▶ 한 줄 요약
   "이미 고른 숫자보다 더 큰 수만 시도" 라는 한 줄 규칙이
   순서 중복(예: [1,2] vs [2,1]) 을 깔끔히 막아 줍니다.

==============================================================================
▣ 우리가 짜야 하는 함수
==============================================================================
combinations(n, k) -> list[list[int]]

내부적으로 헬퍼 함수 backtrack(start, current_combination) 를 재귀 호출합니다.
  - start                 : 이번에 시도해볼 수 있는 가장 작은 숫자
  - current_combination   : 지금까지 골라 둔 숫자들의 리스트 (탐색 중)

==============================================================================
▣ 단계별 가이드 (Level 1, 2, 3)
==============================================================================
[Level 1] 종료 조건만 채워보기
  - current_combination 의 길이가 k 가 되면 결과(result)에 복사본을 추가하고
    이번 가지(branch) 의 탐색을 끝내야 합니다(return).

[Level 2] 가지치기 반복문 채워보기
  - start 부터 n 까지 숫자를 하나씩 시도합니다(`for num in range(start, n + 1)`).

[Level 3] 백트래킹 3단계 채워보기
  - 선택 : current_combination 에 num 을 추가 (.append)
  - 탐색 : backtrack(num + 1, current_combination) 로 더 깊이 들어감
  - 취소 : 방금 추가했던 num 을 다시 제거 (.pop)

==============================================================================
"""


def combinations(n: int, k: int) -> list:
    """
    1 부터 n 까지 숫자 중 k 개를 선택하는 모든 조합을 반환합니다.

    Args:
        n: 전체 숫자 개수 (1, 2, ..., n)
        k: 선택할 개수

    Returns:
        모든 조합을 담은 리스트(예: [[1,2], [1,3], ...])
    """
    result = []  # 완성된 조합을 모아 둘 곳

    def backtrack(start: int, current_combination: list) -> None: # 읽는 사람에게 argument 타입 알려주려고
        """
        재귀(백트래킹) 헬퍼 함수.

        Args:
            start: 이번에 시도해볼 수 있는 가장 작은 숫자
            current_combination: 지금까지 골라 둔 숫자들 (탐색 중)
        """

        # ──────────────────────────────────────────────────────────────────
        # [Level 1] 종료 조건 (Base Case)
        # ──────────────────────────────────────────────────────────────────
        # 힌트:
        # - current_combination 의 길이가 k 와 같다면 조합이 완성된 것입니다.
        # - 그러면 그 조합의 "복사본" 을 result 에 넣고 return 합니다.
        # - 왜 복사본?  current_combination 은 이후 .append/.pop 으로 계속 변하기
        #   때문에 그대로 넣으면 모든 조합이 같은 객체를 가리키게 됩니다.
        # - 복사본 만드는 방법: list(current_combination)  또는 current_combination[:]

        # TODO(Level 1): 아래 두 줄을 직접 작성하세요.
        # if len(current_combination) == ...:
        #     result.append(...)
        #     return
        
        if len(current_combination) == k:
          result.append(list(current_combination))
          return

        # ──────────────────────────────────────────────────────────────────
        # [Level 2] 가지치기 반복문
        # ──────────────────────────────────────────────────────────────────
        # 힌트:
        # - 이번에는 start 부터 n 까지 숫자를 하나씩 시도해 봅니다.
        # - 반복문 변수 이름은 num 으로 추천 (의미: "이번에 고를 숫자").
        #
        # TODO(Level 2): 아래 한 줄을 작성하세요.
        for num in range(start, n+1):

            # ──────────────────────────────────────────────────────────────
            # [Level 3] 백트래킹 3단계
            # ──────────────────────────────────────────────────────────────
            # 힌트:
            #   1) 선택(Choose)  : current_combination 에 num 추가
            #   2) 탐색(Explore) : backtrack(num + 1, current_combination)
            #   3) 취소(Unchoose): current_combination 의 마지막 요소를 제거
            #
            # TODO(Level 3): 아래 세 줄을 작성하세요.
            # current_combination.append(...)
            # backtrack(..., current_combination)
            # current_combination.pop()
            current_combination.append(num)
            # print(num+1, current_combination)
            backtrack(num+1, current_combination)
            current_combination.pop()

    # 처음 호출: 시작 숫자는 1, 지금까지 고른 숫자는 비어 있음
    backtrack(1, [])
    return result



# ============================================================================
# (이 함수는 직접 채울 필요 없음 — itertools 로 만든 비교/검증용 정답)
# ============================================================================
def combinations_itertools_compare(n: int, k: int) -> list:
    """파이썬 표준 라이브러리로 만든 동일 결과 (정답 비교용)"""
    from itertools import combinations as comb
    return [list(c) for c in comb(range(1, n + 1), k)]


